"""Static checks on the pages. The storefront and the dashboard both run the Haybarn build
of DuckDB-Wasm, and the version is pinned in several places in each (preloads, the import,
the bundle URLs). If those drift apart a page quietly loads two copies of the engine, or an
extension that doesn't match — so check they agree.   make test
"""
import os
import re
import unittest

PUBLIC = os.path.join(os.path.dirname(__file__), "public")
PIN = re.compile(r"@haybarn/haybarn-wasm@([0-9][^/'\"]*)")


def page(name):
    with open(os.path.join(PUBLIC, name)) as f:
        return f.read()


class HaybarnPin(unittest.TestCase):
    def versions(self, name):
        return set(PIN.findall(page(name)))

    def test_each_page_pins_exactly_one_version(self):
        for name in ("index.html", "dashboard.html"):
            with self.subTest(page=name):
                self.assertEqual(len(self.versions(name)), 1, f"{name}: {self.versions(name)}")

    def test_both_pages_pin_the_same_version(self):
        self.assertEqual(self.versions("index.html"), self.versions("dashboard.html"))

    def test_the_pin_is_an_exact_release_not_a_floating_tag(self):
        (version,) = self.versions("index.html")
        self.assertRegex(version, r"^\d+\.\d+\.\d+(-rc\d+)?$")

    def test_the_storefront_no_longer_loads_the_old_upstream_build(self):
        self.assertNotIn("@duckdb/duckdb-wasm", page("index.html"))


class Preloads(unittest.TestCase):
    def test_the_storefront_preloads_the_files_its_engine_requests(self):
        html = page("index.html")
        (version,) = set(PIN.findall(html))
        self.assertIn(f"@haybarn/haybarn-wasm@{version}/dist/duckdb-base.wasm", html.split("<style>")[0])
        for ext in ("parquet", "fts", "vss"):
            self.assertIn(f"/core/v2.0.0/wasm_eh/{ext}.duckdb_extension.wasm", html.split("<style>")[0])


class Ranges(unittest.TestCase):
    """public/ranges.json drives the "Ducks near …" filter; it is generated by make_ranges.py."""
    @classmethod
    def setUpClass(cls):
        import json
        import make_ranges
        cls.make = make_ranges
        with open(os.path.join(PUBLIC, "ranges.json"), encoding="utf-8") as f:
            cls.doc = json.load(f)

    def test_every_seeded_species_has_a_range_and_nothing_else_does(self):
        self.assertEqual(set(self.doc["ducks"]), set(self.make.seed_species()))

    def test_ranges_only_name_regions_that_exist(self):
        regions = set(self.doc["regions"])
        for duck, rs in self.doc["ducks"].items():
            with self.subTest(duck=duck):
                self.assertTrue(rs and set(rs) <= regions)
        for city in self.doc["cities"]:
            self.assertIn(city["region"], regions)

    def test_the_file_is_what_make_ranges_generates(self):
        self.assertEqual(self.doc["regions"], self.make.REGIONS)
        self.assertEqual(self.doc["ducks"], self.make.DUCKS)
        self.assertEqual([c["name"] for c in self.doc["cities"]], [c[0] for c in self.make.CITIES])


class DemoNotice(unittest.TestCase):
    """The site is public and looks like a shop, so both pages must say it isn't one."""
    def test_both_pages_say_this_is_not_a_real_shop(self):
        for name in ("index.html", "dashboard.html"):
            with self.subTest(page=name):
                html = page(name)
                self.assertIn('id="demoNote"', html)
                self.assertIn('id="demoNoteClose"', html)   # dismissable
                self.assertIn("not a real shop", html.lower())

    def test_the_notice_is_styled_by_the_shared_stylesheet(self):
        self.assertIn(".demonote", page("xray.css"))


if __name__ == "__main__":
    unittest.main()
